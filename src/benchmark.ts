/**
 * The emitted benchmark: `index.json`, `metadata.json`, and `tasks/`.
 *
 * `index.json` is the only stateful thing in the repo. It maps the stable key
 * `repo:relpath` to a benchmark ID, and those IDs are never reused or
 * renumbered — everything else is derived and can be regenerated from scratch.
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { Corpus, FileFacts, PairReport } from "./corpus.js";
import type { RepoEntry } from "./pairs.js";

export interface IndexEntry {
  id: number;
  /** `repo:relpath` of the TypeScript source. */
  key: string;
  firstSeen: string;
  /** The pair is no longer in the corpus. Kept so its ID is never reissued. */
  tombstoned?: boolean;
}

export interface Index {
  nextId: number;
  entries: IndexEntry[];
}

const INDEX_COMMENT = [
  "Benchmark IDs. The key is `repo:relpath` of the TypeScript source, and an ID",
  "once issued is never reused or renumbered — a task's number is its identity.",
  "IDs are issued to every pair the generator sees, admitted or not, so that a",
  "pair excluded on one machine (a wall-clock timeout, say) keeps its number if",
  "a later run admits it. tasks/ therefore has gaps, by design.",
  "A pair that disappears upstream is tombstoned rather than dropped.",
];

export function loadIndex(indexPath: string): Index {
  if (!existsSync(indexPath)) return { nextId: 1, entries: [] };
  const raw = JSON.parse(readFileSync(indexPath, "utf-8"));
  return { nextId: raw.nextId ?? 1, entries: raw.entries ?? [] };
}

export function writeIndex(indexPath: string, index: Index) {
  const doc = {
    _comment: INDEX_COMMENT,
    nextId: index.nextId,
    entries: [...index.entries].sort((a, b) => a.id - b.id),
  };
  writeFileSync(indexPath, JSON.stringify(doc, null, 2) + "\n");
}

/**
 * Give every pair in this run an ID, minting new ones in key order so a first
 * run is reproducible, and tombstone anything indexed that the run did not see.
 */
export function reconcileIndex(index: Index, reports: PairReport[], today: string): Map<string, number> {
  const byKey = new Map(index.entries.map(e => [e.key, e]));
  const seen = new Set<string>();

  for (const r of [...reports].sort((a, b) => a.key.localeCompare(b.key))) {
    seen.add(r.key);
    const existing = byKey.get(r.key);
    if (existing) {
      delete existing.tombstoned;
      continue;
    }
    const entry: IndexEntry = { id: index.nextId++, key: r.key, firstSeen: today };
    index.entries.push(entry);
    byKey.set(r.key, entry);
  }

  for (const entry of index.entries) {
    if (!seen.has(entry.key)) entry.tombstoned = true;
  }

  return new Map([...byKey].map(([key, e]) => [key, e.id]));
}

export function taskFileName(id: number): string {
  return `${String(id).padStart(4, "0")}.dfy`;
}

export interface TaskMetadata {
  id: number;
  file: string;
  key: string;
  repo: string;
  branch: string;
  relpath: string;
  /** Recorded opportunistically; the working tree is used as-is, dirty or not. */
  head?: string;
  /** Applied identically to the reference solution and to a candidate. */
  verify: { timeLimit?: number; flags: string[] };
  gen: FileFacts;
  solution: FileFacts;
  sizeDiffBytes: number;
  addedLines: number;
  /** Added lines that are neither blank nor a whole-line comment — a better
   *  difficulty proxy than raw size, and just as cheap. */
  addedCodeLines: number;
  /** How long the reference solution took to verify, on the generating machine. */
  referenceVerifySeconds: number;
}

export function buildMetadata(corpus: Corpus, ids: Map<string, number>): { tasks: TaskMetadata[]; doc: object } {
  const headFor = new Map(corpus.checkouts.map(c => [c.entry.repo, c.head]));

  const tasks: TaskMetadata[] = corpus.reports
    .filter(r => r.admitted)
    .map(r => {
      const id = ids.get(r.key)!;
      return {
        id,
        file: `tasks/${taskFileName(id)}`,
        key: r.key,
        repo: r.repo,
        branch: r.branch,
        relpath: r.relpath,
        head: headFor.get(r.repo),
        verify: { timeLimit: r.verifyOptions.timeLimit, flags: r.verifyOptions.flags },
        gen: r.gen!,
        solution: r.solution!,
        sizeDiffBytes: r.solution!.bytes - r.gen!.bytes,
        addedLines: r.additions!.addedLines,
        addedCodeLines: r.additions!.addedCodeLines,
        referenceVerifySeconds: r.verify!.seconds,
      };
    })
    .sort((a, b) => a.id - b.id);

  const doc = {
    _comment: [
      "Generated by bin/generate.ts. One entry per benchmark task; excluded pairs",
      "live in reference-report.json with their cause, not here.",
      "`verify` is transcribed from the case study's LemmaScript-files.txt and is",
      "applied to reference and candidate alike. --standard-libraries is absent on",
      "purpose: it is sniffed from the candidate, which may reach for Std. when the",
      "task skeleton does not.",
    ],
    dafnyVersion: corpus.config.dafnyVersion,
    configSource: corpus.config.source,
    taskCount: tasks.length,
    tasks,
  };
  return { tasks, doc };
}

export interface EmitResult {
  written: number;
  refreshed: number;
  drifted: { file: string; key: string }[];
  stale: string[];
}

/**
 * Copy each admitted `.dfy.gen` into `tasks/` under its benchmark ID, byte for
 * byte — a candidate diffs against this file, so a header comment of our own
 * would show up as a line it failed to add.
 */
export function emitTasks(
  tasksDir: string,
  tasks: TaskMetadata[],
  corpus: Corpus,
  opts: { update: boolean; prune: boolean },
): EmitResult {
  mkdirSync(tasksDir, { recursive: true });
  const result: EmitResult = { written: 0, refreshed: 0, drifted: [], stale: [] };
  const expected = new Set(tasks.map(t => taskFileName(t.id)));

  for (const task of tasks) {
    const name = taskFileName(task.id);
    const dest = path.join(tasksDir, name);
    const src = corpus.pairs.get(task.key)!.genPath;

    if (!existsSync(dest)) {
      copyFileSync(src, dest);
      result.written++;
      continue;
    }
    if (readFileSync(dest).equals(readFileSync(src))) continue;
    // The upstream .gen moved under an existing task. Refreshing changes what
    // the task *is*, so it takes --update rather than happening quietly.
    if (!opts.update) {
      result.drifted.push({ file: name, key: task.key });
      continue;
    }
    copyFileSync(src, dest);
    result.refreshed++;
  }

  for (const name of readdirSync(tasksDir)) {
    if (!name.endsWith(".dfy") || expected.has(name)) continue;
    result.stale.push(name);
    if (opts.prune) rmSync(path.join(tasksDir, name));
  }

  return result;
}

/**
 * `tasks/ATTRIBUTION.md` — which upstream each task derives from, and under
 * what licence.
 *
 * A task file is a Dafny skeleton compiled from someone else's TypeScript, so
 * it is a derived work and the upstream notice has to travel with it. Generated
 * rather than hand-maintained for the obvious reason: a hand-written attribution
 * file goes stale the first time a task is added.
 */
export function buildAttribution(tasks: TaskMetadata[], repos: RepoEntry[]): string {
  const licenseOf = new Map(repos.map(r => [r.repo, r.license]));
  const byRepo = new Map<string, TaskMetadata[]>();
  for (const t of tasks) {
    if (!byRepo.has(t.repo)) byRepo.set(t.repo, []);
    byRepo.get(t.repo)!.push(t);
  }

  const lines = [
    "# Attribution",
    "",
    "Every file in this directory is a Dafny skeleton that LemmaScript compiled",
    "from TypeScript in the repository named below, and is a derived work of it.",
    "The upstream licence governs the task file; this repository's own licence",
    "covers the validator, the generator, and the metadata.",
    "",
    "Generated by `bin/generate.ts` — do not edit by hand.",
    "",
  ];

  for (const repo of [...byRepo.keys()].sort()) {
    const ts = byRepo.get(repo)!.sort((a, b) => a.id - b.id);
    const license = licenseOf.get(repo) ?? "unknown";
    lines.push(`## ${repo}`, "", `Licence: **${license}** · branch \`${ts[0].branch}\``, "");
    if (license === "unlicensed") {
      lines.push(
        "> This repository carries no LICENSE file. The tasks below are included",
        "> on the understanding that the upstream is owned by the same party as",
        "> this benchmark; anyone redistributing them should confirm that.",
        "",
      );
    }
    lines.push("| task | source path |", "|---|---|");
    for (const t of ts) lines.push(`| \`${path.basename(t.file)}\` | \`${t.relpath}\` |`);
    lines.push("");
  }

  return lines.join("\n");
}
