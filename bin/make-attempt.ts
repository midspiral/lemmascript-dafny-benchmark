#!/usr/bin/env -S npx tsx
/**
 * make-attempt — assemble an isolated directory in which someone (or something)
 * can attempt one benchmark task.
 *
 * The directory is deliberately self-contained, with **no path back to this
 * repo**. That is not tidiness, it is the whole point: `metadata.json` names
 * the upstream repository and relpath for every task, and the reference
 * solutions sit in sibling checkouts, so an attempt that can reach the
 * benchmark can read the answer. What gets copied is the task, the validator,
 * and nothing else — not `metadata.json`, not the rest of `tasks/`.
 *
 * The validator is copied rather than imported for the same reason, and it is
 * cheap to copy: two files, no npm dependencies, only Node builtins.
 *
 * Usage:
 *   make-attempt <task-id> [--out=<dir>]
 */

import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { flag } from "../src/cli.js";
import type { TaskMetadata } from "../src/benchmark.js";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const taskArg = process.argv.slice(2).find(a => !a.startsWith("--"));
if (!taskArg) {
  console.error("Usage: make-attempt <task-id> [--out=<dir>]");
  process.exit(2);
}

const metadata = JSON.parse(readFileSync(path.join(repoRoot, "metadata.json"), "utf-8")) as { tasks: TaskMetadata[] };
const id = parseInt(path.basename(taskArg).replace(/\.dfy$/, ""), 10);
const task = metadata.tasks.find(t => t.id === id);
if (!task) {
  console.error(`No task ${taskArg}. metadata.json has ${metadata.tasks.length} tasks.`);
  process.exit(2);
}

const outDir = path.resolve(flag("out", path.join(repoRoot, "attempts", String(id).padStart(4, "0")))!);
const benchDir = path.join(outDir, ".bench");
if (existsSync(outDir)) {
  console.error(`${outDir} already exists — remove it or pass --out=<dir>.`);
  process.exit(2);
}
mkdirSync(benchDir, { recursive: true });

const taskPath = path.join(repoRoot, task.file);

// The pristine copy the diff is taken against, and the working copy to edit.
// Two files rather than one so that editing the working copy cannot destroy
// the thing it is measured against.
copyFileSync(taskPath, path.join(benchDir, "task.dfy.gen"));
copyFileSync(taskPath, path.join(outDir, "solution.dfy"));

for (const f of ["validator.ts", "banned.ts"]) {
  copyFileSync(path.join(repoRoot, "src", f), path.join(benchDir, f));
}

// Without this the directory is not standalone: tsx resolves module type by
// walking up to the nearest package.json, so an attempt dir placed anywhere
// outside this repo is treated as CommonJS and the checker's top-level await
// fails to parse. Found by relocating an attempt dir to /tmp, which is exactly
// where they will live.
writeFileSync(
  path.join(outDir, "package.json"),
  JSON.stringify({ name: `attempt-${String(task.id).padStart(4, "0")}`, private: true, type: "module" }, null, 2) + "\n",
);

// The task's verify options are inlined, so the attempt is held to exactly the
// budget the reference solution was.
writeFileSync(
  path.join(benchDir, "check.ts"),
  `/** Generated by make-attempt for task ${task.id}. Run: npx tsx .bench/check.ts */
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validate } from "./validator.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const result = await validate(path.join(here, "task.dfy.gen"), path.join(here, "..", "solution.dfy"), {
  timeLimit: ${JSON.stringify(task.verify.timeLimit)},
  extraFlags: ${JSON.stringify(task.verify.flags)},
});

const a = result.additions;
const v = result.verify;
console.log(\`additions-only  \${a.status}\`);
if (a.deletedLines) console.log(\`  \${a.deletedLines} line(s) removed or modified: \${a.deletedSamples[0]?.trim()}\`);
for (const m of a.bannedMatches) console.log(\`  banned (\${m.pattern}): \${m.text.trim()}\`);
for (const w of a.weakenedContracts) console.log(\`  \${w.clause} added to a task declaration: \${w.text.trim()}\`);
if (a.status === "not-run") console.log(\`  \${a.notRunReason}\`);
if (a.status === "passed") console.log(\`  +\${a.addedLines} lines (\${a.addedCodeLines} code)\`);

console.log(\`verifies        \${v.status}  (\${v.seconds}s)\`);
if (v.timedOut) console.log("  killed at the wall clock");
if (v.timeouts) console.log(\`  \${v.timeouts} procedure(s) ran out of time\`);
for (const e of v.errorSamples) console.log(\`  error at line \${e}\`);
for (const w of v.disqualifyingWarnings) console.log(\`  \${w.category} at line \${w.line}\`);
if (v.status === "not-run") console.log(\`  \${v.notRunReason}\`);
if (v.errors > v.errorSamples.length) console.log(\`  (\${v.errors - v.errorSamples.length} more error(s))\`);

console.log(result.passed ? "\\nPASS" : "\\nFAIL");
process.exit(result.passed ? 0 : 1);
`,
);

const limit = task.verify.timeLimit ? `${task.verify.timeLimit}s per procedure` : "Dafny's default (30s per procedure)";
const flags = task.verify.flags.length ? task.verify.flags.join(" ") : "none";

// The prompt lives in PROMPT.md at the repo root so its wording can be edited
// without touching this script. Only the per-task facts are substituted.
const substitutions: Record<string, string> = {
  TASK_ID: String(task.id).padStart(4, "0"),
  BUDGET: limit,
  FLAGS: flags,
  DAFNY_FLAGS: task.verify.flags.length ? `${task.verify.flags.join(" ")} ` : "",
};

let prompt = readFileSync(path.join(repoRoot, "PROMPT.md"), "utf-8")
  .replace(/^<!--\s*TEMPLATE[\s\S]*?-->\n/, "")
  .replace(/\{\{(\w+)\}\}/g, (whole, name: string) => substitutions[name] ?? whole);

// A placeholder the script does not know about would otherwise ship to the
// attempter as literal `{{FOO}}`. Fail instead, so the template and the script
// cannot drift apart.
const unresolved = [...new Set([...prompt.matchAll(/\{\{(\w+)\}\}/g)].map(m => m[1]))];
if (unresolved.length) {
  console.error(`PROMPT.md uses unknown placeholder(s): ${unresolved.map(u => `{{${u}}}`).join(", ")}`);
  console.error(`Known: ${Object.keys(substitutions).map(k => `{{${k}}}`).join(", ")}`);
  process.exit(2);
}

writeFileSync(path.join(outDir, "PROMPT.md"), prompt);

console.log(`attempt dir: ${outDir}`);
console.log(`  task ${task.id} — ${task.addedCodeLines} code lines in the reference solution`);
console.log(`  budget: ${limit}, flags: ${flags}`);
console.log(`\nStart a session there and point it at PROMPT.md.`);
